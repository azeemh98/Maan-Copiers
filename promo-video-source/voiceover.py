SR=24000; out=np.zeros(int(56*SR),np.float32); rep=[]
for st,en,txt in L:
    slot=en-st-0.1; sp=1.1
    while True:
        a,sr=k.create(txt,voice=V,speed=sp,lang='hi')
        # trim silence
        nz=np.where(np.abs(a)>0.01)[0]; a=a[max(0,nz[0]-200):nz[-1]+800]
        d=len(a)/sr
        if d<=slot or sp>=1.4: break
        sp=min(1.4,sp*d/slot+0.02)
    i=int(st*SR); j=min(len(out),i+len(a)); out[i:j]+=a[:j-i]
    rep.append((st,round(d,2),round(slot,2),round(sp,2)))
out/=max(1e-6,np.abs(out).max())/0.95
sf.write('voice.wav',out,SR)
for r in rep: print(r, 'OVER' if r[1]>r[2] else '')
